"""Starting, watching and stopping one instance on a load generator.

SSH generators get a small runner script per instance in ``<work_dir>/<run_id>/<NN-tag>/`` (mode 0700). The
runner starts the tool under GNU ``timeout`` (the longest allowed run) detached from the SSH session, removes
itself (it holds the environment values) and writes plain files next to it: ``runner.pid``, ``pid`` (of
``timeout``), ``started_at``, ``finished_at``, ``exit_code`` and ``output.log``. LoadLens reads these files to learn the state, so a test keeps running
and stays observable when LoadLens restarts, and ``timeout`` stops it even if LoadLens never comes back.

Stopping sends the tool's signal to ``timeout``, which passes it on to the tool and its process group;
after the grace period the whole group is killed. Every value that reaches the remote shell is quoted.
"""

from __future__ import annotations

import base64
import io
import logging
import posixpath
import shlex
import threading
from typing import Any, Mapping, Optional, Protocol

from ..generators import Generator, SshSettings
from ..tools import CommandLine, ToolTemplate, class_name_from_path, render_version_command
from .base import (
    LOG_TAIL_BYTES,
    SCRIPT_LIST_LIMIT,
    SKIPPED_DIRS,
    CheckReport,
    GeneratorError,
    LaunchPlan,
    LaunchResult,
    Probe,
)

logger = logging.getLogger(__name__)

KILL_AFTER_SECONDS = 60
COMMAND_TIMEOUT_SEC = 30


class RemoteShell(Protocol):
    def run(self, script: str, stdin: Optional[bytes] = None, timeout: float = COMMAND_TIMEOUT_SEC) -> tuple[int, str, str]:
        """Runs a POSIX sh script on the generator: (exit status, stdout, stderr)."""


# ---- remote scripts (pure functions, tested without a generator) --------------------------------

q = shlex.quote


def instance_dir(generator: Generator, run_id: str, index: int, tag: str) -> str:
    return posixpath.join(generator.work_dir, run_id, f"{index + 1:02d}-{tag}")


def runner_script(directory: str, command: CommandLine, max_seconds: int, kill_after: int = KILL_AFTER_SECONDS) -> str:
    """The runner of one instance.

    Environment values are exported inside the runner, not passed as ``env NAME=value`` arguments, so they
    are not visible in the process list; the runner file (mode 0600) removes itself once the tool started,
    so the values do not stay on the generator after the run.
    """
    argv = " ".join(q(arg) for arg in command.argv)
    exports = [f"export {name}={q(value)}" for name, value in sorted(command.env.items())]
    lines = [
        "#!/bin/sh",
        "# Generated by LoadLens for one load test instance. LoadLens reads the files next to this script.",
        "umask 077",
        f"D={q(directory)}",
        'cd "$D" || exit 1',
        "echo $$ > runner.pid",
        'finish() { date +%s > "$D/finished_at"; echo "$1" > "$D/exit_code.tmp" && mv "$D/exit_code.tmp" "$D/exit_code"; exit 0; }',
        # A relative working directory resolves against the home directory, like in an SSH session.
        'cd "$HOME" 2>/dev/null',
        f'if ! cd {q(command.cwd)} 2>>"$D/output.log"; then',
        f"  printf 'LoadLens: no working directory %s\\n' {q(command.cwd)} >> \"$D/output.log\"",
        '  rm -f "$D/runner.sh"',
        "  finish 126",
        "fi",
        *exports,
        'date +%s > "$D/started_at"',
        f'timeout -s TERM -k {int(kill_after)} {int(max_seconds)} {argv} >> "$D/output.log" 2>&1 < /dev/null &',
        'echo $! > "$D/pid"',
        # sh keeps reading this script through its open descriptor after the file is removed.
        'rm -f "$D/runner.sh"',
        "wait $!",
        "finish $?",
        "",
    ]
    return "\n".join(lines)


def launch_script(directory: str) -> str:
    """Stores the runner from stdin and starts it detached. A directory that already has a runner is left alone.

    ``umask 077``: the runner holds the environment values until the tool starts, other users must not read it.
    """
    return "\n".join([
        "umask 077",
        f"D={q(directory)}",
        'if [ -f "$D/runner.pid" ]; then cat > /dev/null; echo already; exit 0; fi',
        'mkdir -p "$D" || exit 3',
        'cat > "$D/runner.sh" || exit 3',
        'cd "$D" || exit 3',
        "nohup sh ./runner.sh > /dev/null 2>&1 < /dev/null &",
        "echo launched",
    ])


def probe_script(directory: str) -> str:
    return "\n".join([
        f"D={q(directory)}",
        'if [ ! -d "$D" ]; then echo missing=1; echo "now=$(date +%s)"; exit 0; fi',
        'cd "$D" || exit 3',
        "for f in started_at finished_at exit_code; do",
        '  if [ -f "$f" ]; then printf \'%s=%s\\n\' "$f" "$(head -c 32 "$f" | tr -d \'\\r\\n\')"; fi',
        "done",
        'if [ -f runner.pid ] && kill -0 "$(cat runner.pid)" 2>/dev/null; then echo alive=1; else echo alive=0; fi',
        'echo "now=$(date +%s)"',
    ])


def signal_script(directory: str, signal: str) -> str:
    return "\n".join([
        f"D={q(directory)}",
        'p=$(cat "$D/pid" 2>/dev/null) || { echo gone; exit 0; }',
        f'if kill -s {q(signal)} "$p" 2>/dev/null; then echo sent; else echo gone; fi',
    ])


def kill_script(directory: str) -> str:
    # timeout runs in its own process group (GNU coreutils), so the group takes the tool's children with it.
    return "\n".join([
        f"D={q(directory)}",
        'p=$(cat "$D/pid" 2>/dev/null) || { echo gone; exit 0; }',
        'kill -s KILL -- "-$p" 2>/dev/null || kill -s KILL "$p" 2>/dev/null',
        "echo killed",
    ])


def control_script(directory: str, cwd: str, argv: tuple[str, ...]) -> str:
    """Runs a tool control command (soft stop, status) in the working directory of the instance."""
    command = " ".join(q(arg) for arg in argv)
    return "\n".join([
        'cd "$HOME" 2>/dev/null',
        f"cd {q(cwd or directory)} 2>/dev/null || cd {q(directory)} 2>/dev/null",
        f"{command} 2>&1",
    ])


def logs_script(directory: str, max_bytes: int) -> str:
    return f"tail -c {int(max_bytes)} {q(posixpath.join(directory, 'output.log'))} 2>/dev/null; exit 0"


def list_scripts_script(scripts_dir: str, globs: list[str]) -> str:
    names = " -o ".join(f"-name {q(pattern)}" for pattern in globs) or "-name '*'"
    pruned = " -o ".join(f"-name {q(name)}" for name in SKIPPED_DIRS)
    return "\n".join([
        f"cd {q(scripts_dir)} 2>/dev/null || {{ echo __missing__; exit 0; }}",
        f"find . -maxdepth 6 \\( {pruned} \\) -prune -o -type f \\( {names} \\) -print 2>/dev/null | head -n {SCRIPT_LIST_LIMIT}",
    ])


def check_script(generator: Generator, tools: Mapping[str, ToolTemplate]) -> str:
    lines = [
        'echo "uname=$(uname -sm 2>/dev/null)"',
        "if timeout --version 2>/dev/null | head -n 1 | grep -q GNU; then echo timeout=gnu;"
        " elif command -v timeout > /dev/null 2>&1; then echo timeout=other; else echo timeout=missing; fi",
        "if command -v nohup > /dev/null 2>&1; then echo nohup=ok; else echo nohup=missing; fi",
        f"if mkdir -p {q(generator.work_dir)} 2>/dev/null && [ -w {q(generator.work_dir)} ]; then echo work_dir=ok; else echo work_dir=fail; fi",
    ]
    if generator.scripts_dir:
        lines.append(f"if [ -d {q(generator.scripts_dir)} ]; then echo scripts_dir=ok; else echo scripts_dir=missing; fi")
    for tool_id, tool in tools.items():
        if not generator.offers(tool_id) or "{exe}" not in tool.command:
            continue
        exe = generator.executable(tool)
        base = generator.scripts_dir_for(tool_id) or "/"
        lines.append(
            f"(cd {q(base)} 2>/dev/null || cd /; if command -v {q(exe)} > /dev/null 2>&1; then echo {q('tool:' + tool_id + '=found')};"
            f" else echo {q('tool:' + tool_id + '=missing')}; fi)"
        )
        version = render_version_command(tool, exe)
        if version:
            argv = " ".join(q(arg) for arg in version)
            lines.append(
                f"(cd {q(base)} 2>/dev/null || cd /; v=$(timeout 20 {argv} 2>&1 | head -n 1 | tr -d '\\r');"
                f" printf '%s=%s\\n' {q('version:' + tool_id)} \"$v\")"
            )
    return "\n".join(lines)


def parse_key_values(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in (text or "").splitlines():
        key, sep, value = line.partition("=")
        if sep:
            out[key.strip()] = value.strip()
    return out


def _number(value: Optional[str]) -> Optional[float]:
    try:
        return float(value) if value not in (None, "") else None
    except ValueError:
        return None


def parse_probe(text: str) -> Probe:
    values = parse_key_values(text)
    now = _number(values.get("now"))
    if values.get("missing") == "1":
        return Probe(state="missing", remote_now=now)
    started = _number(values.get("started_at"))
    finished = _number(values.get("finished_at"))
    code_text = values.get("exit_code")
    if code_text not in (None, ""):
        try:
            code = int(code_text)
        except ValueError:
            code = None
        return Probe(state="exited", started_at=started, finished_at=finished, exit_code=code, remote_now=now)
    if values.get("alive") == "1":
        return Probe(state="running" if started else "starting", started_at=started, remote_now=now)
    return Probe(state="dead", started_at=started, remote_now=now)


def parse_script_list(text: str, kind: str) -> Optional[list[str]]:
    """Relative paths (or class names) of the scripts; ``None`` when the directory does not exist."""
    lines = [line.strip() for line in (text or "").splitlines() if line.strip()]
    if lines[:1] == ["__missing__"]:
        return None
    paths = sorted({line[2:] if line.startswith("./") else line for line in lines})
    if kind == "class":
        return sorted({class_name_from_path(path) for path in paths})
    return paths


# ---- SSH ---------------------------------------------------------------------------------------


def _paramiko():
    try:
        import paramiko
    except ModuleNotFoundError as exc:  # pragma: no cover - paramiko is in requirements.txt
        raise GeneratorError("Для генераторов по SSH нужен пакет paramiko (pip install paramiko)") from exc
    return paramiko


def host_entry(host: str, port: int) -> str:
    return host if port == 22 else f"[{host}]:{port}"


def parse_host_key(text: str):
    paramiko = _paramiko()
    parts = str(text or "").split()
    if len(parts) < 2:
        raise GeneratorError("Ключ хоста задан неверно: ожидается «тип base64», например ssh-ed25519 AAAA…")
    try:
        return paramiko.PKey.from_type_string(parts[0], base64.b64decode(parts[1]))
    except Exception as exc:
        raise GeneratorError(f"Ключ хоста не разбирается: {exc}") from exc


def load_private_key(text: str, passphrase: str = ""):
    paramiko = _paramiko()
    for key_class in (paramiko.Ed25519Key, paramiko.ECDSAKey, paramiko.RSAKey):
        try:
            return key_class.from_private_key(io.StringIO(text.strip() + "\n"), password=passphrase or None)
        except paramiko.PasswordRequiredException as exc:
            raise GeneratorError("Приватный ключ зашифрован: укажите парольную фразу") from exc
        except Exception:  # another key type or a wrong passphrase: try the next class
            continue
    raise GeneratorError("Приватный ключ не распознан: нужен ключ OpenSSH или PEM (ed25519, ECDSA или RSA)")


def key_fingerprint(key) -> str:
    import hashlib

    digest = hashlib.sha256(key.asbytes()).digest()
    return "SHA256:" + base64.b64encode(digest).decode().rstrip("=")


class SshShell:
    """One cached SSH connection; reconnects once when the cached one broke."""

    def __init__(self, settings: SshSettings, pin_host_key: bool = True) -> None:
        self._settings = settings
        self._pin = pin_host_key
        self._client = None
        self._lock = threading.Lock()
        self.server_key: str = ""
        self.server_fingerprint: str = ""

    def _connect(self):
        paramiko = _paramiko()
        cfg = self._settings
        client = paramiko.SSHClient()
        if self._pin:
            if not cfg.host_key:
                raise GeneratorError(
                    "Ключ хоста генератора не закреплён: откройте генератор в настройках и нажмите «Проверить»"
                )
            key = parse_host_key(cfg.host_key)
            client.get_host_keys().add(host_entry(cfg.host, cfg.port), key.get_name(), key)
            client.set_missing_host_key_policy(paramiko.RejectPolicy())
        else:
            client.set_missing_host_key_policy(paramiko.AutoAddPolicy())
        pkey = load_private_key(cfg.private_key, cfg.passphrase) if cfg.private_key else None
        try:
            client.connect(
                cfg.host,
                port=cfg.port,
                username=cfg.username,
                pkey=pkey,
                password=cfg.password or None,
                look_for_keys=False,
                allow_agent=False,
                timeout=cfg.connect_timeout,
                banner_timeout=cfg.connect_timeout,
                auth_timeout=cfg.connect_timeout,
            )
        except paramiko.BadHostKeyException as exc:
            client.close()
            raise GeneratorError(
                f"Ключ хоста изменился: сервер предъявил {key_fingerprint(exc.key)}, закреплён {key_fingerprint(exc.expected_key)}. "
                "Если сервер переустановлен, очистите «Ключ хоста» в настройках генератора, введите пароль или ключ заново "
                "и проверьте подключение"
            ) from exc
        except paramiko.AuthenticationException as exc:
            client.close()
            raise GeneratorError("SSH отказал во входе: проверьте пользователя, ключ или пароль") from exc
        except paramiko.SSHException as exc:
            client.close()
            raise GeneratorError(f"Ошибка SSH: {exc}") from exc
        except OSError as exc:
            client.close()
            raise GeneratorError(f"Не удалось подключиться к {cfg.host}:{cfg.port}: {exc}") from exc
        transport = client.get_transport()
        if transport is not None:
            transport.set_keepalive(30)
            remote = transport.get_remote_server_key()
            self.server_key = f"{remote.get_name()} {remote.get_base64()}"
            self.server_fingerprint = key_fingerprint(remote)
        return client

    def _exec(self, client, script: str, stdin: Optional[bytes], timeout: float) -> tuple[int, str, str]:
        transport = client.get_transport()
        if transport is None or not transport.is_active():
            raise EOFError("SSH connection is closed")
        # The login shell may be fish or zsh: run the script in sh explicitly.
        stdin_file, stdout_file, stderr_file = client.exec_command(f"sh -c {q(script)}", timeout=timeout)
        channel = stdout_file.channel
        try:
            if stdin:
                stdin_file.write(stdin)
                stdin_file.flush()
            channel.shutdown_write()
            out = stdout_file.read()
            err = stderr_file.read()
            status = channel.recv_exit_status()
            return status, out.decode("utf-8", "replace"), err.decode("utf-8", "replace")
        finally:
            channel.close()

    def run(self, script: str, stdin: Optional[bytes] = None, timeout: float = COMMAND_TIMEOUT_SEC) -> tuple[int, str, str]:
        with self._lock:
            for attempt in (1, 2):
                if self._client is None:
                    self._client = self._connect()
                try:
                    return self._exec(self._client, script, stdin, timeout)
                except GeneratorError:
                    raise
                except Exception as exc:
                    self.close_locked()
                    if attempt == 2:
                        raise GeneratorError(f"Связь с генератором прервалась: {exc}") from exc
            raise GeneratorError("Связь с генератором прервалась")  # pragma: no cover

    def close_locked(self) -> None:
        if self._client is not None:
            try:
                self._client.close()
            except Exception:
                pass
            self._client = None

    def close(self) -> None:
        with self._lock:
            self.close_locked()


class SshExecutor:
    enforces_deadline = True
    supports_signals = True
    supports_control = True

    def __init__(self, generator: Generator, shell: RemoteShell) -> None:
        self.generator = generator
        self.shell = shell

    def _run(self, script: str, stdin: Optional[bytes] = None, timeout: float = COMMAND_TIMEOUT_SEC) -> str:
        status, out, err = self.shell.run(script, stdin=stdin, timeout=timeout)
        if status != 0:
            detail = (err or out).strip()[-500:]
            raise GeneratorError(f"Команда на генераторе завершилась с кодом {status}{': ' + detail if detail else ''}")
        return out

    def launch(self, plan: LaunchPlan) -> LaunchResult:
        ref = plan.ref
        out = self._run(launch_script(ref), stdin=runner_script(ref, plan.command, plan.max_seconds).encode("utf-8"))
        word = out.strip().splitlines()[-1:] or [""]
        if word[0] not in ("launched", "already"):
            raise GeneratorError(f"Генератор не подтвердил запуск: {out.strip()[:200]}")
        return LaunchResult(ref=ref, already_running=word[0] == "already")

    def probe(self, ref: str) -> Probe:
        return parse_probe(self._run(probe_script(ref)))

    def signal(self, ref: str, signal: str, grace_seconds: int = 30) -> None:
        self._run(signal_script(ref, signal))

    def kill(self, ref: str) -> None:
        self._run(kill_script(ref))

    def logs(self, ref: str, max_bytes: int = LOG_TAIL_BYTES) -> str:
        return self._run(logs_script(ref, max_bytes))

    def cleanup(self, ref: str) -> None:
        """The instance directory stays: it is small and holds the full log."""
        return None

    def control(self, ref: str, argv: tuple[str, ...], cwd: str = "") -> tuple[int, str]:
        status, out, err = self.shell.run(control_script(ref, cwd, argv), timeout=COMMAND_TIMEOUT_SEC)
        return status, (out + err).strip()

    def list_scripts(self, scripts_dir: str, tool: ToolTemplate) -> Optional[list[str]]:
        out = self._run(list_scripts_script(scripts_dir, list(tool.scripts_glob)), timeout=20)
        return parse_script_list(out, tool.script_kind)


_SHELLS: dict[str, tuple[tuple, SshShell]] = {}
_SHELLS_LOCK = threading.Lock()


def shell_for(generator: Generator) -> SshShell:
    """Cached connection per generator; a settings change opens a new one."""
    if generator.ssh is None:
        raise GeneratorError(f"Генератор «{generator.title}» не подключается по SSH")
    identity = generator.ssh.identity()
    with _SHELLS_LOCK:
        cached = _SHELLS.get(generator.id)
        if cached and cached[0] == identity:
            return cached[1]
        if cached:
            cached[1].close()
        shell = SshShell(generator.ssh)
        _SHELLS[generator.id] = (identity, shell)
        return shell


def _check_message(values: dict[str, str], generator: Generator, tools: Mapping[str, ToolTemplate]) -> tuple[bool, list[str], list[str]]:
    """(usable, problems, found tool ids) from the answers of the check script."""
    problems: list[str] = []
    if values.get("timeout") == "missing":
        problems.append("нет утилиты timeout (GNU coreutils)")
    elif values.get("timeout") == "other":
        problems.append("timeout не из GNU coreutils: остановка может не дойти до дочерних процессов")
    if values.get("nohup") == "missing":
        problems.append("нет утилиты nohup")
    if values.get("work_dir") != "ok":
        problems.append(f"рабочий каталог {generator.work_dir} не создаётся или недоступен для записи")
    if generator.scripts_dir and values.get("scripts_dir") != "ok":
        problems.append(f"каталога скриптов {generator.scripts_dir} нет")
    found = [tool_id for tool_id in tools if values.get(f"tool:{tool_id}") == "found"]
    missing = [tool_id for tool_id in tools if values.get(f"tool:{tool_id}") == "missing"]
    # Only tools the generator lists explicitly are expected; with an empty list every tool is optional.
    problems.extend(
        f"не найден {tools[tool_id].title} ({generator.executable(tools[tool_id])})"
        for tool_id in missing
        if tool_id in generator.tools
    )
    fatal = values.get("work_dir") != "ok" or values.get("timeout") == "missing" or values.get("nohup") == "missing"
    return not fatal, problems, found


def check_ssh_generator(generator: Generator, tools: Mapping[str, ToolTemplate]) -> CheckReport:
    """Connects (pinning the host key when none is set), checks utilities, directories and tools."""
    assert generator.ssh is not None
    pin = bool(generator.ssh.host_key)
    shell = SshShell(generator.ssh, pin_host_key=pin)
    try:
        status, out, err = shell.run(check_script(generator, tools), timeout=60)
    except GeneratorError as exc:
        return CheckReport(ok=False, message=str(exc))
    finally:
        shell.close()
    values = parse_key_values(out)
    ok, problems, found = _check_message(values, generator, tools)
    titles = [tools[tool_id].title for tool_id in found]
    versions = {tool_id: values[f"version:{tool_id}"] for tool_id in found if values.get(f"version:{tool_id}")}
    details: dict[str, Any] = {
        "system": values.get("uname", ""),
        "tools_found": found,
        "tools_missing": [tool_id for tool_id in tools if values.get(f"tool:{tool_id}") == "missing"],
        "versions": versions,
        "host_key": shell.server_key,
        "host_key_fingerprint": shell.server_fingerprint,
        "host_key_pinned": pin,
    }
    parts = [f"Подключение есть ({values.get('uname') or 'система не определена'})"]
    parts.append(f"инструменты: {', '.join(titles)}" if titles else "инструменты не найдены")
    if not pin and shell.server_key:
        parts.append(f"ключ хоста {shell.server_fingerprint} ещё не закреплён: подтвердите, что доверяете ему, и сохраните генератор")
    if problems:
        parts.append(f"проблемы: {'; '.join(problems)}")
    if status != 0 and not out:
        failure = f"Проверка на генераторе не выполнилась: {(err or '').strip()[:300]}"
        return CheckReport(ok=False, message=failure, details=details, connected=True, problems=[failure])
    return CheckReport(ok=ok, message="; ".join(parts), details=details, connected=True, problems=problems)


